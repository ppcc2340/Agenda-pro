import { v7 as uuidv7 } from "uuid";
import { z } from "zod";

/** Branded ids so the compiler refuses to mix a ClientId with a WorkspaceId (docs/12 §2). */
export type WorkspaceId = string & { readonly __brand: "WorkspaceId" };
export type UserId = string & { readonly __brand: "UserId" };
export type ClientId = string & { readonly __brand: "ClientId" };
export type TaskId = string & { readonly __brand: "TaskId" };
export type AuditId = string & { readonly __brand: "AuditId" };

export const WorkspaceId = z.string().uuid().transform((v) => v as WorkspaceId);
export const UserId = z.string().uuid().transform((v) => v as UserId);
export const ClientId = z.string().uuid().transform((v) => v as ClientId);
export const TaskId = z.string().uuid().transform((v) => v as TaskId);

/** Time-ordered UUID v7, generated by the application (docs/03 §Reglas 6). */
export const newId = (): string => uuidv7();
export const newWorkspaceId = (): WorkspaceId => uuidv7() as WorkspaceId;
export const newUserId = (): UserId => uuidv7() as UserId;
export const newAuditId = (): AuditId => uuidv7() as AuditId;
